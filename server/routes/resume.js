const PREMIUM_TEMPLATES  = new Set(['creative', 'minimal', 'executive']);
const ALL_TEMPLATES      = { corporate, creative, minimal, executive };

// ── Watermark ─────────────────────────────────────────────────
function addWatermark(doc) {
  const PW = doc.page.width;
  const PH = doc.page.height;

  doc.save();
  doc.translate(PW / 2, PH / 2);
  doc.rotate(-45);
  doc.font('Helvetica-Bold').fontSize(56).fillColor('#D1D5DB')
     .text('Generated by AWE-OS', -190, -28, { lineBreak: false, characterSpacing: 1 });
     
  doc.restore();

  doc.font('Helvetica').fontSize(8).fillColor('#9CA3AF')
     .text(
       'Generated with AWE-OS Resume Builder (Free Plan) · Upgrade to remove watermark',
       0, PH - 22, { width: PW, align: 'center', lineBreak: false }
     );
}

// ── POST /api/generate-resume ──────────────────────────────────
router.post('/generate-resume', async (req, res) => {
  const { name, template = FREE_TEMPLATE, ...rest } = req.body;

  if (!name || !name.trim()) {
    return res.status(400).json({ error: 'Name is required' });
  }

  // ===== NEW CODE START =====
  // Check DB for premium status — never trust client-sent flag
  let isDbPremium = false;
  const authHeader = req.headers.authorization;
  if (authHeader?.startsWith('Bearer ')) {
    try {
      const payload = jwt.verify(authHeader.slice(7), process.env.JWT_SECRET);
      const { data } = await supabase
        .from('users')
        .select('is_premium')
        .eq('id', payload.userId)
        .maybeSingle();
      isDbPremium = data?.is_premium || false;
    } catch (err) {
      console.error('[generate-resume] token/db error:', err.message);
      // Invalid/expired token or Supabase error — treat as free user
    }
  }

  const resolvedTemplate =
    isDbPremium && ALL_TEMPLATES[template] ? template : FREE_TEMPLATE;
  const applyWatermark = !isDbPremium;
  // ===== NEW CODE END =====

  const generate = ALL_TEMPLATES[resolvedTemplate] || ALL_TEMPLATES[FREE_TEMPLATE];

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${name.trim().replace(/\s+/g, '_')}_Resume.pdf"`
  );

  try {
    const doc = new PDFDocument({ margin: 0, size: 'A4' });
    doc.pipe(res);

    generate(doc, { name: name.trim(), ...rest });

    if (applyWatermark) addWatermark(doc);

    doc.end();
  } catch (err) {
    console.error('PDF generation error:', err);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to generate PDF' });
    }
  }
});

