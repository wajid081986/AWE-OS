// ── POST /api/create-order ─────────────────────────────────────
router.post('/create-order', requireAuth, async (req, res) => {
  try {
    const order = await razorpay.orders.create({
      amount:   EXPECTED_AMOUNT,
      currency: EXPECTED_CURRENCY,
      receipt:  `receipt_${Date.now()}`,
    });

    return res.json({ success: true, order });
  } catch (err) {
    console.error('Razorpay create-order error:', err.message);
    return res.status(500).json({ success: false, error: 'Failed to create order' });
  }
});

// ── Zod schema for verify-payment ─────────────────────────────
const VerifySchema = z.object({
  razorpay_order_id:   z.string().min(1),
  razorpay_payment_id: z.string().min(1),
  razorpay_signature:  z.string().min(1),
});

// ── POST /api/verify-payment ───────────────────────────────────
router.post('/verify-payment', requireAuth, async (req, res) => {
  const parsed = VerifySchema.safeParse(req.body);
  if (!parsed.success) {
    return res.status(400).json({ success: false, error: 'Invalid payment data' });
  }

  const { razorpay_order_id, razorpay_payment_id, razorpay_signature } = parsed.data;

  try {
    // 1. Verify HMAC signature
    const expectedSignature = crypto
      .createHmac('sha256', process.env.RAZORPAY_KEY_SECRET)
      .update(`${razorpay_order_id}|${razorpay_payment_id}`)
      .digest('hex');

    if (expectedSignature !== razorpay_signature) {
      return res.status(400).json({ success: false, error: 'Signature mismatch' });
    }

    // 2. Verify order amount and currency with Razorpay API
    const order = await razorpay.orders.fetch(razorpay_order_id);
    if (!order || order.amount !== EXPECTED_AMOUNT || order.currency !== EXPECTED_CURRENCY) {
      return res.status(400).json({ success: false, error: 'Order amount mismatch' });
    }

    // 3. Prevent duplicate premium updates
    const { data: user, error: fetchErr } = await supabase
      .from('users')
      .select('is_premium, razorpay_payment_id')
      .eq('id', req.user.userId)
      .single();

    if (fetchErr) throw fetchErr;

    if (user?.is_premium) {
      return res.json({ success: true, message: 'Already premium' });
    }

    // 4. Update DB — never overwrite existing razorpay_payment_id
    const updateData = { is_premium: true };
    if (!user?.razorpay_payment_id) {
      updateData.razorpay_payment_id = razorpay_payment_id;
      updateData.razorpay_order_id   = razorpay_order_id;
    }

    const { data: updated, error: updateErr } = await supabase
      .from('users')
      .update(updateData)
      .eq('id', req.user.userId)
      .eq('is_premium', false)
      .select('id')
      .maybeSingle();

    if (updateErr) throw updateErr;

    // 0 rows updated = concurrent request already upgraded this user
    if (!updated) {
      return res.json({ success: true, message: 'Payment verified' });
    }

    return res.json({ success: true, message: 'Payment verified' });
  } catch (err) {
    console.error('Verify payment error:', err.message);
    return res.status(500).json({ success: false, error: 'Verification failed' });
  }
});
